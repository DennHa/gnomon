const DICTS: Record<Lang, Record<MsgKey, Msg>> = { en, de };
export const LANGUAGE_NAMES: Record<Lang, string> = { en: 'English', de: 'Deutsch' };

const systemLanguage = (): Lang => (typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('de') ? 'de' : 'en');
export const resolveLanguage = (pref?: LanguagePref): Lang => (pref === 'en' || pref === 'de' ? pref : systemLanguage());

let current: Lang = resolveLanguage('system');
export const getLang = () => current;
export function setLanguage(pref?: LanguagePref) {
  current = resolveLanguage(pref);
}

/** Locale for dates and times: German or British English (24-hour clock, day before month). */
export const locale = () => (current === 'de' ? 'de-DE' : 'en-GB');

const fill = (s: string, vars?: Vars) => (vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s);

/** Translates a key; for plural messages pass the count as `n`. */
export function t(key: MsgKey, vars?: Vars): string {
  const msg = DICTS[current][key] ?? en[key];
  if (typeof msg === 'string') return fill(msg, vars);
  const n = Number(vars?.n ?? 0);
  return fill(new Intl.PluralRules(locale()).select(n) === 'one' ? msg.one : msg.other, vars);
}

/** The raw "tray.*" templates in the current language, for the native menu, dialogs and notifications in main. */
export function trayStrings(): Record<string, string> {
  const dict = DICTS[current];
  return Object.fromEntries(Object.keys(en).filter((k) => k.startsWith('tray.')).map((k) => [k.slice(5), dict[k as MsgKey] as string]));
}

/** Applies the language setting before children render, and keeps <html lang> in sync. */
export function useLanguage(pref?: LanguagePref) {
  setLanguage(pref);
  const lang = current;
  useLayoutEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  return lang;
}
